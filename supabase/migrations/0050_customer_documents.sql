-- Customer documents: work orders, proposals and contracts issued to a homeowner for a specific lead/project.
--
-- Built on the existing contract-template engine (contract_templates + immutable published versions,
-- merge fields, PDF renderer, e-signature requests). New here:
--   * contract_templates gains a document type, supported jurisdictions and an explicit ADMIN APPROVAL for use by the
--     assistant/contractors. Nothing is usable for customer documents until an admin approves a specific published version.
--   * customer_documents (+ immutable versions + immutable events) tie a document to its lead (customer + project) and
--     contractor company, snapshot the approved template text, and record who approved every send/signature request.
-- All writes go through the server (service role) after explicit authorization checks; users get SELECT only.
-- Additive and safe to re-run.

alter table public.contract_templates
  add column if not exists doc_type text not null default 'agreement' check (doc_type in ('agreement', 'work_order', 'proposal', 'contract')),
  add column if not exists jurisdictions text[] not null default '{}',
  add column if not exists assistant_approved_version integer check (assistant_approved_version is null or assistant_approved_version >= 1),
  add column if not exists assistant_approved_by uuid references public.profiles(id) on delete set null,
  add column if not exists assistant_approved_at timestamptz;

create table if not exists public.customer_documents (
  id                   uuid primary key default gen_random_uuid(),
  doc_type             text not null check (doc_type in ('work_order', 'proposal', 'contract')),
  doc_no               bigint generated by default as identity unique,
  title                text not null check (char_length(btrim(title)) between 1 and 200),
  lead_id              uuid not null references public.leads(id) on delete restrict,
  contractor_id        uuid not null references public.contractors(id) on delete restrict,
  template_id          uuid not null references public.contract_templates(id) on delete restrict,
  template_version_id  uuid not null references public.contract_template_versions(id) on delete restrict,
  template_name        text not null,
  template_version_no  integer not null,
  template_sha256      text not null check (template_sha256 ~ '^[0-9a-f]{64}$'),
  jurisdiction         text check (jurisdiction is null or char_length(jurisdiction) <= 10),
  -- Snapshot of the APPROVED template text. Never edited by the assistant or the customer-document UI.
  sections             jsonb not null check (jsonb_typeof(sections) = 'array'),
  variables            jsonb not null default '{}'::jsonb check (jsonb_typeof(variables) = 'object'),
  customer             jsonb not null default '{}'::jsonb check (jsonb_typeof(customer) = 'object'),
  signers              jsonb not null default '[]'::jsonb check (jsonb_typeof(signers) = 'array'),
  status               text not null default 'draft' check (status in ('draft', 'sent', 'voided')),
  current_version_no   integer not null default 1,
  signing_document_id  uuid references public.signing_documents(id) on delete restrict,
  signing_version_id   uuid references public.signing_versions(id) on delete restrict,
  sent_at              timestamptz,
  sent_by              uuid references public.profiles(id) on delete set null,
  created_by           uuid references public.profiles(id) on delete set null,
  created_via          text not null default 'assistant' check (created_via in ('assistant', 'app')),
  created_at           timestamptz not null default now(),
  updated_at           timestamptz not null default now()
);
create index if not exists idx_customer_documents_lead on public.customer_documents (lead_id, created_at desc);
create index if not exists idx_customer_documents_contractor on public.customer_documents (contractor_id, created_at desc);
drop trigger if exists trg_customer_documents_updated on public.customer_documents;
create trigger trg_customer_documents_updated before update on public.customer_documents
  for each row execute function public.set_updated_at();

-- Once sent, the content is frozen. Only status/void bookkeeping may change.
create or replace function public.customer_documents_guard() returns trigger language plpgsql as $$
begin
  if tg_op = 'DELETE' then
    if old.sent_at is not null then raise exception 'customer_documents:locked' using errcode = 'P0001'; end if;
    return old;
  end if;
  if old.sent_at is not null then
    if new.title is distinct from old.title or new.sections is distinct from old.sections or new.variables is distinct from old.variables
       or new.customer is distinct from old.customer or new.signers is distinct from old.signers or new.lead_id is distinct from old.lead_id
       or new.contractor_id is distinct from old.contractor_id or new.template_version_id is distinct from old.template_version_id
       or new.current_version_no is distinct from old.current_version_no or new.sent_at is distinct from old.sent_at then
      raise exception 'customer_documents:locked' using errcode = 'P0001';
    end if;
  end if;
  return new;
end $$;
drop trigger if exists trg_customer_documents_guard on public.customer_documents;
create trigger trg_customer_documents_guard before update or delete on public.customer_documents
  for each row execute function public.customer_documents_guard();

-- Every saved revision is kept (append-only).
create table if not exists public.customer_document_versions (
  id              uuid primary key default gen_random_uuid(),
  document_id     uuid not null references public.customer_documents(id) on delete cascade,
  version_no      integer not null check (version_no >= 1),
  title           text not null,
  variables       jsonb not null,
  content_sha256  text not null check (content_sha256 ~ '^[0-9a-f]{64}$'),
  reason          text not null check (reason in ('created', 'edited')),
  created_by      uuid references public.profiles(id) on delete set null,
  created_via     text not null default 'assistant' check (created_via in ('assistant', 'app')),
  created_at      timestamptz not null default now(),
  unique (document_id, version_no)
);

-- Who approved what, and when (append-only audit trail).
create table if not exists public.customer_document_events (
  id             bigint generated always as identity primary key,
  document_id    uuid not null references public.customer_documents(id) on delete cascade,
  event_type     text not null check (event_type in ('created', 'edited', 'signature_approved', 'signature_requested', 'signature_failed', 'voided')),
  actor_user_id  uuid references public.profiles(id) on delete set null,
  via            text not null default 'assistant' check (via in ('assistant', 'app')),
  metadata       jsonb not null default '{}'::jsonb,
  created_at     timestamptz not null default clock_timestamp()
);
create index if not exists idx_customer_document_events_doc on public.customer_document_events (document_id, id);

create or replace function public.customer_documents_forbid_change() returns trigger language plpgsql as $$
begin
  if tg_op = 'DELETE' and not exists (select 1 from public.customer_documents d where d.id = old.document_id) then return old; end if;
  raise exception 'customer_documents:immutable' using errcode = 'P0001';
end $$;
drop trigger if exists trg_customer_document_versions_immutable on public.customer_document_versions;
create trigger trg_customer_document_versions_immutable before update or delete on public.customer_document_versions
  for each row execute function public.customer_documents_forbid_change();
drop trigger if exists trg_customer_document_events_immutable on public.customer_document_events;
create trigger trg_customer_document_events_immutable before update or delete on public.customer_document_events
  for each row execute function public.customer_documents_forbid_change();

alter table public.assistant_actions
  add column if not exists document_id uuid references public.customer_documents(id) on delete set null;

alter table public.customer_documents enable row level security;
alter table public.customer_document_versions enable row level security;
alter table public.customer_document_events enable row level security;

drop policy if exists customer_documents_select on public.customer_documents;
create policy customer_documents_select on public.customer_documents for select
  using (public.is_admin() or (contractor_id is not null and contractor_id = public.auth_contractor_id()));
drop policy if exists customer_document_versions_select on public.customer_document_versions;
create policy customer_document_versions_select on public.customer_document_versions for select
  using (exists (select 1 from public.customer_documents d where d.id = document_id));
drop policy if exists customer_document_events_select on public.customer_document_events;
create policy customer_document_events_select on public.customer_document_events for select
  using (exists (select 1 from public.customer_documents d where d.id = document_id));
-- No client write policies: the server (service role) writes after authorization checks.

comment on table public.customer_documents is
  'Work orders, proposals and contracts issued to a homeowner for a lead. Template text is a snapshot of an admin-approved published version.';
